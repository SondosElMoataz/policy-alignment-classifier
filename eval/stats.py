"""Uncertainty and paired comparisons for completed evaluation runs.

Reads predictions.jsonl from run directories (no inference) and writes a Markdown
comparison with Wilson 95% intervals and exact paired McNemar tests.

    uv run python eval/stats.py experiments/reports/final_A100_policy_v1_1
"""
import argparse
import json
import math
import sys
from itertools import combinations
from pathlib import Path

VERDICTS = ("allow", "violation", "escalate")
KINDS = ("user_input", "model_output", "tool_call", "tool_response")


def wilson(k, n, z=1.959964):
    """Wilson score interval; returns (low, high) or None when n == 0."""
    if not n:
        return None
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return max(0.0, centre - half), min(1.0, centre + half)


def mcnemar_exact(b, c):
    """Two-sided exact binomial McNemar p-value on discordant pairs b, c."""
    n = b + c
    if n == 0:
        return 1.0
    tail = sum(math.comb(n, i) for i in range(0, min(b, c) + 1)) / 2 ** n
    return min(1.0, 2 * tail)


def load(run_dir):
    return [json.loads(line) for line in (Path(run_dir) / "predictions.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]


def correct(r):
    return r["pred"] == r["gold"] and r["pred"] in VERDICTS and not r.get("error")


def rates(records):
    """Headline counts as (numerator, denominator), matching eval/run_eval.metrics."""
    valid = [r for r in records if r["pred"] in VERDICTS and not r.get("error")]
    gold = lambda label: sum(r["gold"] == label for r in records)
    return {
        "accuracy": (sum(correct(r) for r in records), len(records)),
        "violation recall": (sum(r["gold"] == r["pred"] == "violation" for r in valid), gold("violation")),
        "unsafe-allow rate": (sum(r["gold"] == "violation" and r["pred"] == "allow" for r in valid), gold("violation")),
        "false-block rate": (sum(r["gold"] == "allow" and r["pred"] in ("violation", "escalate") for r in valid), gold("allow")),
        "escalation recall": (sum(r["gold"] == r["pred"] == "escalate" for r in valid), gold("escalate")),
        "invalid": (len(records) - len(valid), len(records)),
    }


def fmt(k, n):
    if not n:
        return "n/a"
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {k / n:.1%} [{lo:.0%}–{hi:.0%}]"


def percentile(values, q):
    ordered = sorted(values)
    return ordered[max(0, math.ceil(q / 100 * len(ordered)) - 1)] if ordered else None


def report(root):
    root = Path(root)
    runs = {d.name: load(d) for d in sorted(root.iterdir()) if (d / "predictions.jsonl").exists()}
    if not runs:
        raise SystemExit(f"No run directories with predictions.jsonl under {root}")
    splits = sorted({name.rsplit("_", 1)[-1] for name in runs})
    out = ["# Final comparison with uncertainty", "",
           f"Generated by `eval/stats.py` from `{root.as_posix()}/*/predictions.jsonl`. No inference was run.",
           "Brackets are Wilson 95% intervals. Invalid/errored outputs count as incorrect for accuracy.", ""]
    for split in splits:
        names = [n for n in runs if n.endswith("_" + split)]
        out += [f"## {split} split (n = {len(runs[names[0]])})", "", "| Metric | " + " | ".join(names) + " |",
                "|---|" + "---|" * len(names)]
        table = {n: rates(runs[n]) for n in names}
        for metric in table[names[0]]:
            out.append(f"| {metric} | " + " | ".join(fmt(*table[n][metric]) for n in names) + " |")
        out += ["", "**Accuracy by target event kind**", "", "| Kind | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
        for kind in KINDS:
            cells = []
            for n in names:
                subset = [r for r in runs[n] if r["event_kind"] == kind]
                cells.append(f"{sum(map(correct, subset))}/{len(subset)}")
            out.append(f"| {kind} | " + " | ".join(cells) + " |")
        out += ["", "**Paired exact McNemar test on per-case correctness**", "",
                "b = cases only the first run gets right; c = only the second. p < 0.05 would indicate a difference beyond chance.", "",
                "| Pair | b | c | p |", "|---|---|---|---|"]
        for a, b in combinations(names, 2):
            ra, rb = {r["id"]: correct(r) for r in runs[a]}, {r["id"]: correct(r) for r in runs[b]}
            only_a = sum(ra[i] and not rb[i] for i in ra)
            only_b = sum(rb[i] and not ra[i] for i in ra)
            out.append(f"| {a} vs {b} | {only_a} | {only_b} | {mcnemar_exact(only_a, only_b):.3f} |")
        out += ["", "**Latency (wall-clock ms per event, nearest rank) and tokens per event**", "",
                "| Run | P50 | P95 | P99 | mean | prompt tok (mean) | completion tok (mean) |", "|---|---|---|---|---|---|---|"]
        for n in names:
            lat = [r["latency_ms"] for r in runs[n] if r.get("latency_ms") is not None]
            pt = [r["prompt_tokens"] for r in runs[n] if r.get("prompt_tokens") is not None]
            ct = [r["completion_tokens"] for r in runs[n] if r.get("completion_tokens") is not None]
            mean = lambda xs: f"{sum(xs) / len(xs):.0f}" if xs else "n/a"
            out.append(f"| {n} | {percentile(lat, 50):.0f} | {percentile(lat, 95):.0f} | {percentile(lat, 99):.0f} | {mean(lat)} | {mean(pt)} | {mean(ct)} |")
        out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("root", type=Path, help="Directory containing one subdirectory per run")
    parser.add_argument("--out", type=Path, help="Markdown output path (default: <root>/comparison.md)")
    args = parser.parse_args()
    text = report(args.root)
    target = args.out or args.root / "comparison.md"
    target.write_text(text, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
